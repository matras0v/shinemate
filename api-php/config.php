// Получатель заявок с сайта — тот же адрес, что указан в контактах на
// самом сайте (src/data/company.ts, поле leadEmail).
define('CONTACT_TO', 'shinemate_russia@mail.ru');

// Адрес отправителя (From) и имя. На shared-хостинге почта доходит
// надёжнее, если этот адрес реально существует как почтовый ящик на
// домене сайта — иначе часть провайдеров (в т.ч. mail.ru) может уводить
// такие письма в спам из-за несовпадения домена отправителя с доменом,
// с которого физически уходит письмо (SPF/DKIM). Если почтового ящика
// webmaster@shinemate-russia.ru на хостинге нет — замените на реально
// существующий адрес на этом домене или на адрес, который хостинг-панель
// REG.RU показывает как "адрес отправителя по умолчанию" для mail().
define('CONTACT_FROM', 'webmaster@shinemate-russia.ru');
define('CONTACT_FROM_NAME', 'ShineMate Russia — сайт');

// Ограничение частоты отправки с одного IP — защита от спама/перебора,
// не требует куки/сессии у посетителя.
define('RATE_LIMIT_FILE', __DIR__ . '/data/contact-rate.json');
define('RATE_LIMIT_MAX', 5);
define('RATE_LIMIT_WINDOW', 600);

// Форма, отправленная раньше этого числа секунд после показа, считается
// ботовой (человек физически не успевает заполнить поля быстрее).
define('MIN_SUBMIT_SECONDS', 3);
