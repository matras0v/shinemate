/**
 * Товар «как его сейчас видит пользователь»: карточка плюс выбранное
 * исполнение. Если исполнение переопределяет название, подзаголовок,
 * описание, характеристики или кадр — возвращается новая позиция с этими
 * значениями, и вся страница (hero, тёмная полоса характеристик, сцены,
 * совместимость) строится уже от неё.
 *
 * Зачем это нужно: в одной карточке «Мойка и подготовка» лежат ведро,
 * сепаратор и микрофибра — разные предметы. Пока страница читала только
 * поля карточки, при выборе микрофибры на экране оставался «Объём ведра
 * 20 л» и описание сепаратора. Теперь несовпадения быть не может: если у
 * исполнения есть свои данные, чужие не показываются.
 */
export function resolveProductView(product: Product, variant?: Variant): Product {
  if (!variant) return product
  const overrides =
    variant.model || variant.kind || variant.lead || variant.specs || variant.image
  if (!overrides) return product
  return {
    ...product,
    model: variant.model ?? product.model,
    kind: variant.kind ?? product.kind,
    lead: variant.lead ?? product.lead,
    specs: variant.specs ?? product.specs,
    image: variant.image ?? product.image,
    imageWidth: variant.imageWidth ?? product.imageWidth,
    imageHeight: variant.imageHeight ?? product.imageHeight,
    /* Комплект поставки относится к конкретному исполнению, а не к группе. */
    includes: variant.specs ? undefined : product.includes,
  }
}

/**
 * Карточка объединяет РАЗНЫЕ предметы, а не размеры одного товара —
 * тогда переключатель должен выглядеть как выбор товара, а не как выбор
 * размера. Признак прямой: у исполнений есть собственные названия.
 */
export const isProductGroup = (p: Product) => p.variants.some((v) => Boolean(v.model))

/**
 * Порядок внутри категории — explicit sortOrder (когда он важен, как у
 * V-Range), а не случайный порядок объявления в файле. Array.sort стабилен,
 * поэтому товары без sortOrder (сравниваются как 0 === 0) сохраняют
 * порядок объявления между собой.
 */
export const productsByCategory = (id: CategoryId) =>
  products.filter((p) => p.category === id).sort((a, b) => (a.sortOrder ?? 0) - (b.sortOrder ?? 0))

export const countByCategory = (id: CategoryId) =>
  products
    .filter((p) => p.category === id)
    .reduce((total, p) => total + p.variants.length, 0)

/** Минимальная РРЦ среди исполнений — для подписи «от …». */
export const minPrice = (p: Product) => {
  const value = Math.min(...p.variants.map((v) => v.rrp))
  return Number.isFinite(value) ? value : null
}

/** «1 вариант / 2 варианта / 5 вариантов» — русское склонение по числу. */
export const variantsLabel = (count: number) => {
  const mod10 = count % 10
  const mod100 = count % 100
  const word =
    mod10 === 1 && mod100 !== 11
      ? 'вариант'
      : [2, 3, 4].includes(mod10) && ![12, 13, 14].includes(mod100)
        ? 'варианта'
        : 'вариантов'
  return `${count} ${word}`
}

/**
 * Соседние модели той же категории, ближайшие по цене — как в магазине,
 * где рядом с товаром стоят реальные альтернативы, а не случайный набор.
 * Ничего не придумывается: и состав, и подписи ниже читаются из тех же
 * полей, что уже есть в карточке товара.
 */
/**
 * Похожие позиции.
 *
 * `pool` позволяет сузить выборку до семейства (роторные к роторным,
 * шерсть к шерсти): раздел не равен семейству — в «Роторных машинках»
 * рядом с EP830 лежит гибкий вал, и предлагать его как «похожую модель»
 * неверно. Если в семействе меньше двух соседей, берём весь раздел,
 * чтобы блок не оставался пустым.
 */
export const getRelatedProducts = (product: Product, max = 3, pool?: Product[]): Product[] => {
  const base = minPrice(product) ?? 0
  const near = (pool ?? []).filter((p) => p.slug !== product.slug)
  const source = near.length >= 2 ? near : productsByCategory(product.category).filter((p) => p.slug !== product.slug)
  return source
    .sort((a, b) => Math.abs((minPrice(a) ?? 0) - base) - Math.abs((minPrice(b) ?? 0) - base))
    .slice(0, max)
}

/** Короткая, честная причина посмотреть на альтернативу — только из реальных полей. */
export const relatedNote = (candidate: Product, current: Product) => {
  const a = minPrice(candidate)
  const b = minPrice(current)
  if (a != null && b != null && a !== b) return a < b ? 'Дешевле' : 'Дороже'
  if (candidate.kind !== current.kind) return candidate.kind
  return categoryTitle(candidate.category)
}

