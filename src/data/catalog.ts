/**
 * Исполнение одной модели — один конкретный физический SKU, а не
 * склеенная строка вида "34114-9 / 34116-9 / 34117-9". Когда исполнение
 * реально различается по двум независимым осям (например, градация И
 * размер, как у кругов), их можно указать через axis1/axis2 — тогда
 * карточка товара покажет два ряда переключателей вместо плоского списка.
 */
export type Variant = {
  sku: string
  label: string
  rrp: number
  /** Первая ось выбора: градация, тип подушки и т.п. */
  axis1?: string
  /** Вторая ось выбора: размер/диаметр. */
  axis2?: string
  /**
   * Официальное фото именно этого исполнения (например, зелёный T120),
   * когда оно реально отличается от фото товара по умолчанию — иначе
   * выбор градации визуально ничего не менял, хотя цвет в тексте другой.
   */
  image?: string
  imageWidth?: number
  imageHeight?: number
  /**
   * Короткая оговорка под фото для конкретного исполнения — когда у
   * вендора нет отдельного фото именно этого размера/цвета и показанное
   * фото визуально отличается (например, круг 4" реально без центрального
   * отверстия, а фото показывает грейд с отверстием 6"/7", других фото у
   * вендора для этого грейда нет).
   */
  note?: string
  /*
   * Собственные данные исполнения.
   *
   * Есть позиции, где «исполнения» — это НЕ размеры одного товара, а
   * разные предметы в одной карточке: у «Мойки и подготовки» это ведро,
   * сепаратор и микрофибра. Пока страница рендерилась только из полей
   * товара, на микрофибре оставался «Объём ведра 20 л», описание
   * рассказывало про сепаратор, а фото показывало салфетки. Поля ниже
   * позволяют исполнению переопределить название, подзаголовок, описание
   * и характеристики — тогда переключатель меняет страницу целиком, а не
   * только цену и артикул.
   */
  model?: string
  kind?: string
  lead?: string
  /** Полностью ЗАМЕНЯЮТ характеристики товара, а не дополняют их. */
  specs?: Spec[]
}

export type Spec = { label: string; value: string }

export type Product = {
  slug: string
  model: string
  category: CategoryId
  /** Короткий подзаголовок: тип инструмента. */
  kind: string
  lead: string
  specs: Spec[]
  includes?: string[]
  variants: Variant[]
  image: string
  imageWidth: number
  imageHeight: number
  /** Выносится в раздел избранных моделей на главной. */
  featured?: boolean
  /**
   * Явный порядок внутри категории — когда порядок принципиален (например,
   * составы V-Range всегда идут V20→V40→V80→V82) и не должен зависеть от
   * случайного порядка в этом файле. По умолчанию — порядок объявления.
   */
  sortOrder?: number
  /** Подпись над рядом переключателей исполнения в drawer (по умолчанию «Градация»). */
  axisLabel?: string
}

